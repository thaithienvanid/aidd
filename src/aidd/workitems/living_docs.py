"""The checks and the generated index behind the product's living documents (the same-change check in `living_work`
covers the rest): the threat models, the metrics dictionary, and the improvement log.

- A Spec's threat delta names threat ids, `T-<COMPONENT>-NN`. Each component has one living model under
  `<docs>/security/threat-models/`, and a delta whose component has no model, or whose id the model does not list, is a
  warning. `aidd new threat-model` writes the folder's index (`README.md`) from the models and the Specs that link them.
- A tracking plan's events fold into the metrics dictionary, so an event is named once.
- An SLO doc's new targets fold into the service card under `<docs>/services/`, so the card stays the current objectives.
- An improvement whose check date has passed with no result is a warning.

Every function takes the paths it reads, because the document types' homes belong to `authoring.REPO_DOCS`. Advice only:
nothing here blocks a Spec.
"""

from __future__ import annotations

import datetime as dt
import os
import re
from pathlib import Path

from aidd.kernel import command_names, documents, regular_files
from aidd.kernel import text as kernel_text
from aidd.workitems import objects, spec_file, status, work_list

THREAT_ID = re.compile(r"\bT-([A-Z][A-Z0-9]*(?:-[A-Z][A-Z0-9]*)*)-(\d{2,})\b")
INDEX_FILE = "README.md"
INDEX_NOTE = "<!-- Generated by `aidd new threat-model` from the models and the Specs that link them. Never edit it. -->"


def table_rows(text: str) -> list[dict[str, str]]:
    """Every row of every Markdown table in `text`, as {lowercase header: cell}; a rule row and a short row are skipped."""
    rows: list[dict[str, str]] = []
    header: list[str] | None = None
    for line in text.splitlines():
        if not line.lstrip().startswith("|"):
            header = None
            continue
        inner = line.strip()[1:]
        cells = [c.strip() for c in (inner[:-1] if inner.endswith("|") else inner).split("|")]
        if header is None:
            header = [c.lower() for c in cells]
        elif not set("".join(cells)) <= set("-: ") and len(cells) >= len(header):
            rows.append(dict(zip(header, cells, strict=False)))
    return rows


def _models_link(root: Path, docs_dir: str) -> str:
    """The link on the way to the threat models' folder, as a path from `root`; "" when there is none. aidd then reads no
    model there and writes no index, because both would land outside the repository."""
    rel = f"{docs_dir.rstrip('/')}/{spec_file.THREAT_MODELS}"
    return rel if regular_files.is_outside(docs_dir.rstrip("/") or ".") else regular_files.link_on_the_way(root, rel)


def _models(root: Path, docs_dir: str) -> dict[str, Path]:
    """The component models in the threat models' folder, by the component's slug: regular files only, and none when a
    link lies on the way to the folder (`_models_link`)."""
    folder = root / docs_dir / spec_file.THREAT_MODELS
    if _models_link(root, docs_dir) or not folder.is_dir():
        return {}
    found = sorted(p for p in folder.glob("*.md") if not p.is_symlink() and p.is_file() and p.name != INDEX_FILE)
    return {kernel_text.slug(p.stem): p for p in found}


def threat_delta_warnings(path: Path, root: Path, data: dict, texts: list[str], docs_dir: str) -> list[str]:
    """A warning for each component whose threat ids the Spec's `texts` name while the component has no model, and, once
    the Spec has asked for approval, for each id its model does not list. Placeholder ids (`T-TODO-01`) count for nothing."""
    named: dict[str, list[str]] = {}
    for text in texts:
        for m in THREAT_ID.finditer(text):
            if m.group(1) != status.PLACEHOLDER:
                named.setdefault(m.group(1), [])
                if m.group(0) not in named[m.group(1)]:
                    named[m.group(1)].append(m.group(0))
    models = _models(root, docs_dir)
    sid, asked = str(data.get("id")), status.spec_status(data) in status.ASKED
    out = []
    for component, ids in named.items():
        slug = kernel_text.slug(component)
        home = f"{docs_dir}/{spec_file.THREAT_MODELS}/{slug}.md"
        more = f" and {len(ids) - 1} more" if len(ids) > 1 else ""
        if slug not in models:
            out.append(
                f"warning: {path}: the threat delta names {ids[0]}{more}, but the component has no model ({home}); "
                f"write it with `aidd new threat-model {command_names.quoted(slug) or '<component>'} --spec {command_names.quoted(sid) or '<ID>'}`"
            )
            continue
        body = regular_files.file_text(root, models[slug], documents.MAX_DOCUMENT_BYTES) or ""
        listed = {m.group(0) for m in THREAT_ID.finditer(body)}
        missing = [i for i in ids if i not in listed] if asked else []
        if missing:
            out.append(
                f"warning: {path}: the threat delta names {', '.join(missing[:3])}{' and more' if len(missing) > 3 else ''}, "
                f"which {home} does not list; bring the model in line with the delta in the same change"
            )
    return out


def _event_names(text: str) -> list[str]:
    """The event names in a document's `## Events` table, with no placeholder."""
    names = []
    for row in table_rows(documents.markdown_section(text, "Events")):
        key = next((k for k in row if k.startswith("event")), "")
        name = row.get(key, "").strip("` ")
        if name and status.PLACEHOLDER not in name:
            names.append(name)
    return names


def event_warnings(path: Path, root: Path, data: dict, dictionary: str) -> list[str]:
    """A warning for each linked tracking plan whose events the metrics dictionary (`dictionary`, a path in the
    repository) does not name, once the Spec has asked for approval. Without the dictionary, nothing."""
    file = root / dictionary
    if status.spec_status(data) not in status.ASKED or not file.is_file():
        return []
    known = set(_event_names(objects.document_text(root, dictionary)))
    out = []
    for d in data.get("docs") or []:
        if not isinstance(d, dict) or d.get("type") != "tracking-plan":
            continue
        for rel in objects.files_matching(root, str(d.get("path"))):
            missing = [e for e in _event_names(objects.document_text(root, rel)) if e not in known]
            if missing:
                out.append(
                    f"warning: {path}: the tracking plan {rel} lists {', '.join(f'`{e}`' for e in missing[:3])}{' and more' if len(missing) > 3 else ''}, "
                    f"which the metrics dictionary {dictionary} does not name; fold each into it in the same change, so an event is named once"
                )
    return out


def _slo_targets(text: str) -> dict[str, str]:
    """The SLI and its new target for each row of an SLO doc's `## SLI changes` table that sets one: not a retired SLI,
    not a placeholder."""
    out = {}
    for row in table_rows(documents.markdown_section(text, "SLI changes")):
        sli, target = row.get("sli", "").strip("` "), row.get("becomes", "").strip("` ")
        if sli and target and not row.get("change", "").lower().startswith("retire") and status.PLACEHOLDER not in sli + target:
            out[sli] = target
    return out


def slo_warnings(path: Path, root: Path, data: dict, services: str) -> list[str]:
    """A warning for each linked SLO doc whose new targets the service cards (`services`, a folder in the repository)
    do not hold, once the Spec has asked for approval: the card's `## SLOs` table needs the same SLI with the same
    target. The warning names both files. A doc with no target to fold, or a Spec that links none, warns nothing."""
    if status.spec_status(data) not in status.ASKED:
        return []
    cards = [c for c in objects.files_matching(root, f"{services}/*.md") if c.endswith(".md")]
    held = {
        (r.get("sli", "").strip("` "), r.get("target", "").strip("` "))
        for c in cards
        for r in table_rows(documents.markdown_section(objects.document_text(root, c), "SLOs"))
    }
    out = []
    for d in data.get("docs") or []:
        if not isinstance(d, dict) or d.get("type") != "slo":
            continue
        for rel in objects.files_matching(root, str(d.get("path"))):
            missing = [sli for sli, target in _slo_targets(objects.document_text(root, rel)).items() if (sli, target) not in held]
            if missing:
                where = ", ".join(cards[:3]) if cards else f"{services}/ (no service card there)"
                out.append(
                    f"warning: {path}: the SLO doc {rel} sets {', '.join(f'`{s}`' for s in missing[:3])}{' and more' if len(missing) > 3 else ''}, "
                    f"which the service card {where} does not hold; fold each into its `## SLOs` table in the same change (`aidd new service-card <name>`)"
                )
    return out


def overdue_improvements(rel: str, text: str, today: dt.date) -> list[str]:
    """A finding for each improvement in the log `text` (named `rel`) whose `Check by` date is before `today` while
    its `Result` is empty. A row without a real date is a placeholder, and counts for nothing."""
    out = []
    for row in table_rows(text):
        try:
            due = dt.date.fromisoformat(row.get("check by", "").strip("`"))
        except ValueError:
            continue
        if due < today and not row.get("result"):
            what = documents.one_line(row.get("improvement", ""), 80)
            out.append(f"{rel}: the improvement {what!r} was due for its check on {due} with no result; write `kept` or `reverted`, with the number it moved")
    return out


def threat_model_index(root: Path, cfg, docs_dir: str) -> str:
    """The index of the threat models: each component, its model, and the Specs that link it; empty with no model."""
    models = _models(root, docs_dir)
    if not models:
        return ""
    found, _ = work_list.read_work(root, cfg)
    linked: dict[str, list[str]] = {}
    for _, d in found:
        for rel in spec_file.threat_models(d, docs_dir) if d.get("type") == "spec" else []:
            linked.setdefault(kernel_text.slug(Path(rel).stem), []).append(str(d.get("id")))
    rows = [
        f"| {kernel_text.md_cell(documents.one_line(p.stem, 80))} | [{kernel_text.md_cell(p.name)}]({p.name}) | "
        f"{', '.join(sorted(dict.fromkeys(linked.get(slug, [])))) or 'none'} |"
        for slug, p in models.items()
    ]
    head = "# Threat models\n\nOne living model per component. A Spec that changes a component links its model and states only its delta.\n\n"
    return f"{INDEX_NOTE}\n\n{head}| Component | Model | Specs that link it |\n| --- | --- | --- |\n" + "\n".join(rows) + "\n"


def write_threat_index(root: Path, cfg, docs_dir: str) -> Path | None:
    """Write the index beside the models, only when it changed; None with no model. A README a person wrote, without
    the generated note on its first line, is theirs, so it is kept."""
    text = threat_model_index(root, cfg, docs_dir)
    if not text:
        return None
    path = root / docs_dir / spec_file.THREAT_MODELS / INDEX_FILE
    if regular_files.link_on_the_way(root, path.relative_to(root)):
        return None  # a link on the way would send the write outside the repository; `index_warnings` names it
    current = regular_files.file_text(root, path, documents.MAX_DOCUMENT_BYTES)
    if current is None and os.path.lexists(path):
        return path  # a device there is never written through
    if current is None or (current.startswith(INDEX_NOTE) and current != text):
        with regular_files.open_for_write(path, text=True) as f:
            f.write(text)
    return path


def index_warnings(root: Path, cfg, docs_dir: str) -> list[str]:
    """A finding when the threat models have no index, or an index that no longer matches them, or when a link on the
    way to them stops aidd from reading them."""
    if link := _models_link(root, docs_dir):
        return [f"{link}: a link, which aidd never follows, so the threat models there are not read and their index is not written; replace it with the folder"]
    expected = threat_model_index(root, cfg, docs_dir)
    path = root / docs_dir / spec_file.THREAT_MODELS / INDEX_FILE
    current = regular_files.file_text(root, path, documents.MAX_DOCUMENT_BYTES)
    if not expected or current == expected or (current is not None and not current.startswith(INDEX_NOTE)):
        return []
    rel = f"{docs_dir}/{spec_file.THREAT_MODELS}/{INDEX_FILE}"
    return [
        f"{rel}: the index of the threat models is {'missing' if current is None else 'out of date'}; `aidd new threat-model <component> --spec <ID> --no-link` writes it again and leaves the Spec as it is"
    ]
